import type { BenchmarkReport } from "@/models/BenchmarkReport";

import { formatBenchmarkMarkdown } from "@/services/formatBenchmarkMarkdown";
import { describe, expect, test } from "vitest";

describe(formatBenchmarkMarkdown, () => {
  const environment = "- Node: v0";
  const report: BenchmarkReport = {
    files: [
      {
        filepath: "",
        groups: [
          {
            benchmarks: [{ mean: 1, name: "", p99: 0, rme: 0, sampleCount: 0 }],
            fullName: " ",
          },
        ],
      },
    ],
  };

  test("renders the environment block and a section per group", () => {
    expect.hasAssertions();

    expect(formatBenchmarkMarkdown(report, environment)).toMatchInlineSnapshot(`
      "# Benchmark results

      Auto-generated by the BenchmarkMarkdownReporter on \`pnpm bench\`, colocated beside the bench file (a
      \`.bench.json\` sits next to it). Diff over time to catch regressions. \`vs base\` is a throughput
      multiplier against each group's baseline
      (the \`native\` task, else the first): \`1.00×\` is the baseline, higher is faster, lower is slower — a
      fast task drifting back toward \`1.00×\` is a regression. \`±rme\` is the relative margin of error.
      Numbers are machine- and commit-dependent (see Environment); only compare runs from the same host.

      ## Environment

      - Node: v0

      ##  

      | task | vs base | mean (ms) | ±rme   | p99 (ms) | samples |
      | ---- | ------- | --------- | ------ | -------- | ------- |
      |      | 1.00×   | 1.0000    | ±0.00% | 0.0000   | 0       |
      "
    `);
  });

  test("derives the vs-base multiplier from the native baseline, faster above 1 and slower below", () => {
    expect.hasAssertions();

    const grouped: BenchmarkReport = {
      files: [
        {
          filepath: "",
          groups: [
            {
              benchmarks: [
                { mean: 2, name: "native", p99: 0, rme: 0, sampleCount: 0 },
                { mean: 1, name: " ", p99: 0, rme: 0, sampleCount: 0 },
                { mean: 4, name: "  ", p99: 0, rme: 0, sampleCount: 0 },
              ],
              fullName: " ",
            },
          ],
        },
      ],
    };
    expect(formatBenchmarkMarkdown(grouped, environment)).toMatchInlineSnapshot(`
      "# Benchmark results

      Auto-generated by the BenchmarkMarkdownReporter on \`pnpm bench\`, colocated beside the bench file (a
      \`.bench.json\` sits next to it). Diff over time to catch regressions. \`vs base\` is a throughput
      multiplier against each group's baseline
      (the \`native\` task, else the first): \`1.00×\` is the baseline, higher is faster, lower is slower — a
      fast task drifting back toward \`1.00×\` is a regression. \`±rme\` is the relative margin of error.
      Numbers are machine- and commit-dependent (see Environment); only compare runs from the same host.

      ## Environment

      - Node: v0

      ##  

      | task   | vs base | mean (ms) | ±rme   | p99 (ms) | samples |
      | ------ | ------- | --------- | ------ | -------- | ------- |
      | native | 1.00×   | 2.0000    | ±0.00% | 0.0000   | 0       |
      |        | 2.00×   | 1.0000    | ±0.00% | 0.0000   | 0       |
      |        | 0.5×    | 4.0000    | ±0.00% | 0.0000   | 0       |
      "
    `);
  });

  test("escapes pipe delimiters in benchmark names", () => {
    expect.hasAssertions();

    const escaped: BenchmarkReport = {
      files: [
        {
          filepath: "",
          groups: [{ benchmarks: [{ mean: 1, name: " | ", p99: 1, rme: 0, sampleCount: 1 }], fullName: " " }],
        },
      ],
    };
    expect(formatBenchmarkMarkdown(escaped, environment)).toMatchInlineSnapshot(`
      "# Benchmark results

      Auto-generated by the BenchmarkMarkdownReporter on \`pnpm bench\`, colocated beside the bench file (a
      \`.bench.json\` sits next to it). Diff over time to catch regressions. \`vs base\` is a throughput
      multiplier against each group's baseline
      (the \`native\` task, else the first): \`1.00×\` is the baseline, higher is faster, lower is slower — a
      fast task drifting back toward \`1.00×\` is a regression. \`±rme\` is the relative margin of error.
      Numbers are machine- and commit-dependent (see Environment); only compare runs from the same host.

      ## Environment

      - Node: v0

      ##  

      | task | vs base | mean (ms) | ±rme   | p99 (ms) | samples |
      | ---- | ------- | --------- | ------ | -------- | ------- |
      |  \\|  | 1.00×   | 1.0000    | ±0.00% | 1.0000   | 1       |
      "
    `);
  });
});
