import type { Plugin } from "vite";

import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { builtinPresets, createUnimport, resolvePreset } from "unimport";

// The ambient file a package's tsconfig includes, beside its manifest. unplugin-auto-import would write it too, but it
// Prepends its own header, with eslint, prettier, oxlint, oxfmt and biome directives in it. Those tools do not read
// This file, so the directives would only silence nothing, and the lint toolchain test reads them as a finding. The
// Body is `unimport`'s output for the same presets, so it is written here with a header that carries no directive
const AUTO_IMPORT_DECLARATIONS_FILE = "auto-imports.d.ts";
const HEADER = "// Generated by @esposter/configuration. Do not edit.\n";

const generateDeclarations = async (presets: readonly (keyof typeof builtinPresets)[]): Promise<string> => {
  // A preset is either the definition or a factory for it, which unplugin-auto-import calls the same way
  const imports = (
    await Promise.all(
      presets.map((name) => {
        const preset = builtinPresets[name];
        return resolvePreset(typeof preset === "function" ? preset() : preset);
      }),
    )
  ).flat();
  const unimport = createUnimport({
    addons: { addons: [{ declaration: (declarations) => `${HEADER}${declarations}\n`, name: "auto-import-header" }] },
    imports,
  });

  return unimport.generateTypeDeclarations({});
};

// Written at each build start from the presets the transform injects, so the declarations and the injected imports
// Cannot drift apart. The transform's own `dts` is off for this reason. The file goes to Vite's resolved root, which is
// The package's own folder even when the root Vitest run loads it as a project from the repository root. A tsdown build
// Has no Vite config, and pnpm runs it in the package's folder, so its working directory is that root
export const autoImportDeclarationsPlugin = (presets: readonly (keyof typeof builtinPresets)[]): Plugin => {
  let root = process.cwd();
  return {
    async buildStart() {
      await writeFile(resolve(root, AUTO_IMPORT_DECLARATIONS_FILE), await generateDeclarations(presets));
    },
    configResolved(config) {
      root = config.root;
    },
    name: "auto-import-declarations",
  };
};
