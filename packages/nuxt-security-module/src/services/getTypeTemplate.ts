import { MODULE_NAME, ROUTE_RULES_HOOK } from "#src/runtime/constants";

// The module's virtual modules and its runtime hook, typed for the server.
// Declared once per build.
// So the app's own server code typechecks the hook a consumer adds to and the virtual modules the plugins import.
export const getTypeTemplate = (): string => `// Generated by ${MODULE_NAME}
import type { ModuleOptions } from '${MODULE_NAME}'

declare module '#${MODULE_NAME}/route-rules.mjs' {
  const routeRules: Record<string, Partial<ModuleOptions>>
  export default routeRules
}

declare module '#${MODULE_NAME}/sri-hashes.mjs' {
  const sriHashes: Record<string, string>
  export default sriHashes
}

declare module 'nitro/types' {
  interface NitroRuntimeHooks {
    '${ROUTE_RULES_HOOK}': (routeRules: Record<string, Partial<ModuleOptions>>) => void | Promise<void>
  }
}

export {}
`;
