import { KIT_MODULE_DIRECTORY } from "#scripts/kit/constants";
import { globSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const GENERATED_DIRECTORY = join("src", "generated", "characterKitMap");
const MAP_NAME = "CharacterIdCreateKitBehaviourMap";
const KIT_MODULE_PATTERN = "*Kit.ts";
const ID_EXPORT_REGEX = /^export const \w+_CHARACTER_ID = (?<id>[\d_]+);/mu;
const CREATE_EXPORT_REGEX = /^export const (?<name>create\w+KitBehaviour) = /mu;
// A module without a declared id is left out of the map, and the map's test then fails on the mismatch
const readKitModule = (directory: string, file: string) => {
  const text = readFileSync(join(directory, file), "utf8");
  const id = ID_EXPORT_REGEX.exec(text)?.groups?.id;
  const createName = CREATE_EXPORT_REGEX.exec(text)?.groups?.name;
  return id && createName ? { createName, file, id } : undefined;
};

// Writes the kit map from every kit module in `KIT_MODULE_DIRECTORY`, each keyed by the character id it declares,
// So a new kit is one module with no shared file edited. Each entry imports its module on demand, so a kit loads only
// When its character joins the party, and the id is written as the module declares it rather than imported, which would
// Load the module with the map. Called from the build's `build:prepare` hook before the barrels are written, so the
// Barrel lists the map too
export const generateCharacterKitMap = (packageDirectory: string): void => {
  const charactersDirectory = join(packageDirectory, "src", KIT_MODULE_DIRECTORY);
  const kitModules = globSync(KIT_MODULE_PATTERN, { cwd: charactersDirectory })
    .map((file) => file.replaceAll("\\", "/"))
    .toSorted()
    .flatMap((file) => {
      const kitModule = readKitModule(charactersDirectory, file);
      return kitModule ? [kitModule] : [];
    })
    // Its entries are in character id order, which is the order `sort-objects` holds the map's keys to
    .toSorted(
      (firstKitModule, secondKitModule) =>
        Number(firstKitModule.id.replaceAll("_", "")) - Number(secondKitModule.id.replaceAll("_", "")),
    );
  const entries = kitModules.map(
    ({ createName, file, id }) =>
      `  ${id}: async () => (await import("#src/${KIT_MODULE_DIRECTORY}/${file.replace(/\.ts$/u, "")}")).${createName},`,
  );
  const text = [
    `// Generated by the genshin-world build from every kit module in src/${KIT_MODULE_DIRECTORY}, each keyed by the`,
    "// character id it declares. Do not edit it: a new kit is one module, and the next build writes this map again.",
    "// Each entry's import() keeps its module out of the entry, so a kit loads only once its character joins the party.",
    'import type { KitBehaviour } from "#src/models/kit/KitBehaviour";',
    'import type { KitRecordReader } from "#src/models/kit/KitRecordReader";',
    "",
    `export const ${MAP_NAME}: Readonly<Record<number, () => Promise<(reader: KitRecordReader) => KitBehaviour>>> = {`,
    ...entries,
    "};",
    "",
  ].join("\n");
  // The folder is the generator's alone, so it is cleared first: a map a rename left behind (a cache restoring an older
  // Build's folder in CI) would otherwise be built beside the current one, importing exports that no longer exist
  const generatedDirectory = join(packageDirectory, GENERATED_DIRECTORY);
  rmSync(generatedDirectory, { force: true, recursive: true });
  mkdirSync(generatedDirectory, { recursive: true });
  writeFileSync(join(generatedDirectory, `${MAP_NAME}.ts`), text);
};
