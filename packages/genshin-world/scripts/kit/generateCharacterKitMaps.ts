import { KIT_MODULE_DIRECTORY, SKILL_GLYPHS_MODULE_DIRECTORY } from "#scripts/kit/constants";
import { globSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const GENERATED_DIRECTORY = join("src", "generated", "characterKitMaps");
const BEHAVIOUR_MAP_NAME = "CharacterIdCreateKitBehaviourMap";
const SKILL_GLYPHS_MAP_NAME = "CharacterIdSkillGlyphsLoaderMap";
const KIT_MODULE_SUFFIX = "Kit.ts";
const SKILL_GLYPHS_MODULE_SUFFIX = "SkillGlyphs.ts";
const ID_EXPORT_REGEX = /^export const \w+_CHARACTER_ID = (?<id>[\d_]+);/mu;
const CREATE_EXPORT_REGEX = /^export const (?<name>create\w+KitBehaviour) = /mu;
const SKILL_GLYPHS_EXPORT_REGEX = /^export const (?<name>\w+_SKILL_GLYPHS): SkillGlyphs = /mu;

// The modules in a directory ending in a suffix, sorted, each with the stem its suffix leaves, which pairs a character's
// Skill glyphs module with its kit module
const readModuleFiles = (directory: string, suffix: string) =>
  globSync(`*${suffix}`, { cwd: directory })
    .map((file) => file.replaceAll("\\", "/"))
    .toSorted()
    .map((file) => ({ file, stem: file.slice(0, -suffix.length), text: readFileSync(join(directory, file), "utf8") }));

// A map of `import()` entries, each loading its module's export on demand, so the module stays out of the entry and loads
// Only once its character joins the party
const writeLoaderMap = (
  generatedDirectory: string,
  {
    comment,
    imports,
    mapName,
    valueType,
  }: { comment: string[]; imports: string[]; mapName: string; valueType: string },
  entries: { directory: string; file: string; id: string; name: string }[],
): void =>
  writeFileSync(
    join(generatedDirectory, `${mapName}.ts`),
    [
      ...comment.map((line) => `// ${line}`),
      ...imports,
      "",
      `export const ${mapName}: Readonly<Record<number, () => Promise<${valueType}>>> = {`,
      ...entries.map(
        ({ directory, file, id, name }) =>
          `  ${id}: async () => (await import("#src/${directory}/${file.replace(/\.ts$/u, "")}")).${name},`,
      ),
      "};",
      "",
    ].join("\n"),
  );

// Writes the maps a character's kit loads with, from the modules in `KIT_MODULE_DIRECTORY` and
// `SKILL_GLYPHS_MODULE_DIRECTORY`: the behaviour map, each kit module keyed by the character id it declares, so a new kit
// Is one module with no shared file edited, and the skill glyphs map, each character's traced icons keyed by the id its kit
// Module of the same stem declares. Each entry imports its module on demand, so a kit and its icons load only when their
// Character joins the party, and the id is written as the module declares it rather than imported, which would load the
// Module with the map. A module without a declared id, or icons without a kit, are left out, and the maps' tests then fail
// On the mismatch. Called from the build's `build:prepare` hook before the barrels are written, so the barrel lists the
// Maps too
export const generateCharacterKitMaps = (packageDirectory: string): void => {
  const sourceDirectory = join(packageDirectory, "src");
  const kitModules = readModuleFiles(join(sourceDirectory, KIT_MODULE_DIRECTORY), KIT_MODULE_SUFFIX).flatMap(
    ({ file, stem, text }) => {
      const id = ID_EXPORT_REGEX.exec(text)?.groups?.id;
      const name = CREATE_EXPORT_REGEX.exec(text)?.groups?.name;
      return id && name ? [{ directory: KIT_MODULE_DIRECTORY, file, id, name, stem }] : [];
    },
  );
  const stemIdMap = new Map(kitModules.map(({ id, stem }) => [stem, id]));
  const skillGlyphsModules = readModuleFiles(
    join(sourceDirectory, SKILL_GLYPHS_MODULE_DIRECTORY),
    SKILL_GLYPHS_MODULE_SUFFIX,
  ).flatMap(({ file, stem, text }) => {
    const id = stemIdMap.get(stem);
    const name = SKILL_GLYPHS_EXPORT_REGEX.exec(text)?.groups?.name;
    return id && name ? [{ directory: SKILL_GLYPHS_MODULE_DIRECTORY, file, id, name }] : [];
  });
  const generatedDirectory = join(packageDirectory, GENERATED_DIRECTORY);
  mkdirSync(generatedDirectory, { recursive: true });
  writeLoaderMap(
    generatedDirectory,
    {
      comment: [
        `Generated by the genshin-world build from every kit module in src/${KIT_MODULE_DIRECTORY}, each keyed by the`,
        "character id it declares. Do not edit it: a new kit is one module, and the next build writes this map again.",
        "Each entry's import() keeps its module out of the entry, so a kit loads only once its character joins the party.",
      ],
      imports: [
        'import type { KitBehaviour } from "#src/models/kit/KitBehaviour";',
        'import type { KitRecordReader } from "#src/models/kit/KitRecordReader";',
      ],
      mapName: BEHAVIOUR_MAP_NAME,
      valueType: "(reader: KitRecordReader) => KitBehaviour",
    },
    kitModules,
  );
  writeLoaderMap(
    generatedDirectory,
    {
      comment: [
        `Generated by the genshin-world build from every skill glyphs module in src/${SKILL_GLYPHS_MODULE_DIRECTORY}, each`,
        "keyed by the character id its kit module of the same stem declares. Do not edit it: a character's traced icons",
        "are one module, and the next build writes this map again. Each entry's import() keeps its module out of the",
        "entry, so the icons load only once their character joins the party, with its kit.",
      ],
      imports: ['import type { SkillGlyphs } from "#src/models/hud/SkillGlyphs";'],
      mapName: SKILL_GLYPHS_MAP_NAME,
      valueType: "SkillGlyphs",
    },
    skillGlyphsModules,
  );
};
