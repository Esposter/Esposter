// The residue a float error leaves beside the value a sum of steps should reach is a sliver short of it.
// Three hundred steps of a sixtieth of a second fall a sliver short of the seconds they make up.
// Steps of points fall a sliver short of their count.
// A residue under a billionth reads as reached, which no real duration or count is this close to.
export const FLOAT_RESIDUE = 1e-9;
