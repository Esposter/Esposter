import type { TypeBenchRow } from "#src/models/benchTypes/TypeBenchRow";

const HEADER_CELLS = ["case", "types", "instantiations"];

// Columns padded to the widest cell, the way the formatter lays out a table, so a format pass never rewrites a result
// This wrote. The compiler version is in the file because a count is that version's, so a compiler bump shows in the
// Diff of every result.
export const formatTypeBenchMarkdown = (rows: TypeBenchRow[], compilerVersion: string): string => {
  const bodyCells = rows.map((row) => [row.name, String(row.types), String(row.instantiations)]);
  const allCells = [HEADER_CELLS, ...bodyCells];
  const widths = HEADER_CELLS.map((_header, column) =>
    Math.max(...allCells.map((cells) => cells[column]?.length ?? 0)),
  );
  const formatRow = (cells: string[]): string =>
    `| ${cells.map((cell, column) => cell.padEnd(widths[column] ?? 0)).join(" | ")} |`;
  const separator = `| ${widths.map((width) => "-".repeat(width)).join(" | ")} |`;

  return [
    "# Type benchmark results",
    "",
    "Auto-generated by `pnpm bench:types` beside its `*.typebench.ts` source. Each row is what its case adds over the",
    "source's own header, so the imports and fixtures every case shares cancel out.",
    "",
    `Compiler: \`tsrs@${compilerVersion}\``,
    "",
    formatRow(HEADER_CELLS),
    separator,
    ...bodyCells.map((cells) => formatRow(cells)),
    "",
  ].join("\n");
};
