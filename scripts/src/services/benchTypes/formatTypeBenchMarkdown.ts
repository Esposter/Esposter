import type { TypeBenchRow } from "#src/models/benchTypes/TypeBenchRow";

const HEADER_CELLS = ["case", "types", "instantiations"];

// Columns padded to the widest cell, the way the formatter lays out a table, so a format pass never rewrites a result
// This wrote. The compiler version is in the file because a count is that version's, and a change to it is the change
// The guard exists to show.
export const formatTypeBenchMarkdown = (rows: TypeBenchRow[], typescriptVersion: string): string => {
  const bodyCells = rows.map((row) => [row.name, String(row.types), String(row.instantiations)]);
  const allCells = [HEADER_CELLS, ...bodyCells];
  const widths = HEADER_CELLS.map((_, column) => Math.max(...allCells.map((cells) => cells[column]?.length ?? 0)));
  const formatRow = (cells: string[]): string =>
    `| ${cells.map((cell, column) => cell.padEnd(widths[column] ?? 0)).join(" | ")} |`;
  const separator = `| ${widths.map((width) => "-".repeat(width)).join(" | ")} |`;

  return [
    "# Type benchmark results",
    "",
    "Auto-generated by `pnpm bench:types` beside its `*.typebench.ts` source, and checked by it: a run whose counts",
    "differ from these fails until `pnpm bench:types -u` rewrites them. Each row is what its case adds over the source's",
    "own header, so the imports and fixtures every case shares cancel out.",
    "",
    `Compiler: \`typescript@${typescriptVersion}\``,
    "",
    formatRow(HEADER_CELLS),
    separator,
    ...bodyCells.map((cells) => formatRow(cells)),
    "",
  ].join("\n");
};
