import { formatTypeBenchMarkdown } from "#src/services/benchTypes/formatTypeBenchMarkdown";
import { describe, expect, test } from "vitest";

describe(formatTypeBenchMarkdown, () => {
  test("a table padded to its widest cell, with the compiler version named", () => {
    expect.hasAssertions();

    expect(
      formatTypeBenchMarkdown(
        [
          { instantiations: 20, name: "Alpha", types: 1 },
          { instantiations: 4, name: "LongerName", types: 300 },
        ],
        "1.0.0",
      ),
    ).toBe(
      [
        "# Type benchmark results",
        "",
        "Auto-generated by `pnpm bench:types` beside its `*.typebench.ts` source, and checked by it: a run whose counts",
        "differ from these fails until `pnpm bench:types -u` rewrites them. Each row is what its case adds over the source's",
        "own header, so the imports and fixtures every case shares cancel out.",
        "",
        "Compiler: `typescript@1.0.0`",
        "",
        "| case       | types | instantiations |",
        "| ---------- | ----- | -------------- |",
        "| Alpha      | 1     | 20             |",
        "| LongerName | 300   | 4              |",
        "",
      ].join("\n"),
    );
  });
});
