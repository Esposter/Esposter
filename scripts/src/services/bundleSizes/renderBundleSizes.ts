import type { BundleSize } from "#src/models/bundleSizes/BundleSize";

import { BUNDLE_SIZES_FILENAME } from "#src/services/bundleSizes/constants";
import { formatSource } from "#src/services/format/formatSource";
import { MEBIBYTE, REPOSITORY_ROOT } from "#src/services/shared/constants";
import { KIBIBYTE } from "@esposter/configuration";

// The largest file first, and equal sizes in the order of their package and file, so the order is the build's alone
const compareBundleSizes = (a: BundleSize, b: BundleSize) =>
  b.bytes - a.bytes ||
  (a.packageName < b.packageName ? -1 : a.packageName > b.packageName ? 1 : a.file < b.file ? -1 : 1);

// The record a commit diffs: one row per built file, the largest first, its exact bytes beside the KiB a reader quotes.
// The file is generated by `pnpm bundle-sizes:gen`, and a workspace test holds it to a fresh build. It is committed as the
// Formatter writes it, so the table's columns are aligned the way the formatter aligns them
export const renderBundleSizes = (bundleSizes: BundleSize[]): string => {
  const totalBytes = bundleSizes.reduce((total, { bytes }) => total + bytes, 0);
  const source = [
    "# Bundle sizes",
    "",
    `Every file a workspace package's build emits, largest first, as \`pnpm bundle-sizes:gen\` writes \`${BUNDLE_SIZES_FILENAME}\`. A size that moves shows up here as a diff.`,
    "",
    "| Package | File | Bytes | KiB |",
    "| :------ | :--- | ----: | --: |",
    ...bundleSizes
      .toSorted(compareBundleSizes)
      .map(
        ({ bytes, file, packageName }) => `| ${packageName} | ${file} | ${bytes} | ${(bytes / KIBIBYTE).toFixed(1)} |`,
      ),
    "",
    `**Total:** ${bundleSizes.length} files, ${totalBytes} bytes, ${(totalBytes / KIBIBYTE).toFixed(1)} KiB, ${(totalBytes / MEBIBYTE).toFixed(2)} MiB`,
    "",
  ].join("\n");
  return formatSource(source, BUNDLE_SIZES_FILENAME, REPOSITORY_ROOT, REPOSITORY_ROOT) ?? source;
};
