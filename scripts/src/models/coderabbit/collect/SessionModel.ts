// The family alias a headless session runs on, never a version (`llm-delegation`): left unpinned, a role runs
// On whatever the family's newest member is, which no log line would have to state. The enum is what a role moved
// To another family — another vendor's, even — changes in one place, and `SessionRoleModelMap` is where a role says
// Which it runs on.
export enum SessionModel {
  Haiku = "haiku",
  Opus = "opus",
}
