// A button's look beyond the raised default: the accent for the one action a panel leads with, danger for one that
// Destroys or stops something, quiet for a mark that floats over content without a surface of its own, field for a
// Trigger that holds a value as a field does, such as a select's, and search for the trigger drawn as the search field
// It opens
export enum UiButtonVariant {
  Accent = "Accent",
  Danger = "Danger",
  Field = "Field",
  Quiet = "Quiet",
  Search = "Search",
}
