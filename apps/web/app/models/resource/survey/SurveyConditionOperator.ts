// A comparison a condition row makes, each member's value spelled as the expression language writes it, so a row's operator is its own text
export enum SurveyConditionOperator {
  Contains = "contains",
  Empty = "empty",
  Equals = "=",
  Greater = ">",
  GreaterOrEquals = ">=",
  Less = "<",
  LessOrEquals = "<=",
  NotContains = "notcontains",
  NotEmpty = "notempty",
  NotEquals = "!=",
}
